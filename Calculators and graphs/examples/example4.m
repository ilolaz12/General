% example4.m
% MATLAB example 4 - trickier plot
%---------------------------------------------------------------

%---------------------------------------------------------------
clear all
close all
%---------------------------------------------------------------

%---------------------------------------------------------------
f = 0:0.01:100;
g = 1./(1 + (f/2).^2);
%---------------------------------------------------------------

%---------------------------------------------------------------
figure(1);
clf
plot(f, g);
grid('on');
%---------------------------------------------------------------

%---------------------------------------------------------------
pause
disp('Setting horizontal scale to logarithmic');
set(gca, 'xscale', 'log');
grid('on');
%---------------------------------------------------------------

%---------------------------------------------------------------
pause
disp('Setting vertical scale to logarithmic');
set(gca, 'xscale', 'linear');
set(gca, 'yscale', 'log');
grid('on');
%---------------------------------------------------------------
