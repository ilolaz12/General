% example5.m
% MATLAB example 5 - cascading systems
%---------------------------------------------------------------

%---------------------------------------------------------------
clear all
close all
%---------------------------------------------------------------

%---------------------------------------------------------------
t = 0:0.001:2;

x = 2*sin(4*pi*t);
y = x.^2;
z = y + 3;
%---------------------------------------------------------------

%---------------------------------------------------------------
figure(1);
clf

subplot(3,1,1);
plot(t, x);
set(gca, 'ylim', [-8 8]);
grid('on');
title('sin 4\pi t');

subplot(3,1,2);
plot(t, y);
set(gca, 'ylim', [-8 8]);
grid('on');
title('sin^2 4\pi t');

subplot(3,1,3);
plot(t, z);
set(gca, 'ylim', [-8 8]);
grid('on');
title('sin^2 ( 4\pi t) + 3');
%---------------------------------------------------------------

